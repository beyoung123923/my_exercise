/**
 * @brief: CRC校验
 * @param {type} None
 * @return: None
 */
uint16_t calc_crc16(uint8_t *buf, uint16_t len)
{
    uint8_t crc_h = 0xff;
    uint8_t crc_l = 0xff;     
    int index;

    while(len--)
    {
    	index = crc_h ^ *(buf++);  /*计算CRC*/
    	crc_h = (uint8_t)(crc_l ^ crc_h_table[index]);
    	crc_l = crc_l_table[index];
    }
    return ((uint16_t)crc_h << 8 | crc_l);
}

